#!/usr/bin/env bash
# Claude Code setup for this hivey checkout. install.sh and `hivey update` run it.
#
# herdr's AGENTS.md (CLAUDE.md links to it) is 300+ lines, mostly herdr's maintainer and release
# process. Claude Code's docs say to keep CLAUDE.md under 200 lines, so this checkout loads a short
# digest instead, without changing herdr's file:
#   CLAUDE.local.md                      the digest (git-ignored via .git/info/exclude)
#   .claude/settings.local.json          claudeMdExcludes: CLAUDE.md and AGENTS.md (other keys kept)
#   .claude/skills/hivey-*/              procedures, loaded only when used
#   .claude/rules/hivey-*.md             rules loaded only when matching files are touched
# Templates live in assets/claude-code/. A file without the "hivey: generated" marker is the
# user's own and is never overwritten. Safe to run again: it only reports what it changed.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
SRC=assets/claude-code
MARK='hivey: generated from assets/claude-code'

put() {  # <template> <destination>
  local src=$1 dest=$2
  if [ -e "$dest" ] && ! grep -q "$MARK" "$dest"; then
    echo "  kept      $ROOT/$dest (yours, not generated by hivey)"
    return
  fi
  if [ -e "$dest" ] && cmp -s "$src" "$dest"; then return; fi
  local what=updated; [ -e "$dest" ] || what=new
  mkdir -p "$(dirname "$dest")"
  cp "$src" "$dest.new" && mv -f "$dest.new" "$dest"
  echo "  $what $(printf '%*s' $((9 - ${#what})) '')$ROOT/$dest"
}

put "$SRC/CLAUDE.local.md" CLAUDE.local.md
for f in "$SRC"/skills/*/SKILL.md "$SRC"/rules/*.md; do
  put "$f" ".claude/${f#"$SRC"/}"
done

# Generated skills and rules that are no longer in the templates.
for f in .claude/skills/hivey-*/SKILL.md .claude/rules/hivey-*.md; do
  [ -e "$f" ] && [ ! -e "$SRC/${f#.claude/}" ] && grep -q "$MARK" "$f" || continue
  rm -f "$f"; rmdir "$(dirname "$f")" 2>/dev/null || true
  echo "  removed   $ROOT/$f"
done

# Keep CLAUDE.local.md out of git without changing herdr's .gitignore.
EXCLUDE=$(git rev-parse --git-path info/exclude 2>/dev/null || true)
case "$EXCLUDE" in ''|/*) ;; *) EXCLUDE="$ROOT/$EXCLUDE" ;; esac
if [ -n "$EXCLUDE" ] && ! grep -qx 'CLAUDE.local.md' "$EXCLUDE" 2>/dev/null; then
  mkdir -p "$(dirname "$EXCLUDE")"
  printf '\n# hivey: the Claude Code digest of AGENTS.md (scripts/claude-code-setup.sh)\nCLAUDE.local.md\n' >>"$EXCLUDE"
  echo "  updated   $EXCLUDE (ignores CLAUDE.local.md)"
fi

# Stop Claude Code loading the full AGENTS.md here, but only when the digest replaces it.
if ! grep -q "$MARK" CLAUDE.local.md 2>/dev/null; then
  echo "  skipped   claudeMdExcludes: CLAUDE.local.md is your own, so AGENTS.md keeps loading"
  exit 0
fi
python3 - "$ROOT" <<'PY'
import json, os, sys
root = sys.argv[1]
path = os.path.join(root, ".claude", "settings.local.json")
want = [os.path.join(root, "CLAUDE.md"), os.path.join(root, "AGENTS.md")]
data = {}
if os.path.exists(path):
    try:
        with open(path) as f:
            data = json.load(f)
    except (OSError, ValueError) as e:
        print(f"  skipped   {path}: not valid JSON ({e}); add claudeMdExcludes by hand")
        sys.exit(0)
    if not isinstance(data, dict):
        print(f"  skipped   {path}: not a JSON object")
        sys.exit(0)
excl = data.get("claudeMdExcludes")
if not isinstance(excl, list):
    excl = []
missing = [p for p in want if p not in excl]
if not missing:
    sys.exit(0)
what = "updated" if os.path.exists(path) else "new"
data["claudeMdExcludes"] = excl + missing
os.makedirs(os.path.dirname(path), exist_ok=True)
with open(path + ".new", "w") as f:
    json.dump(data, f, indent=2)
    f.write("\n")
os.replace(path + ".new", path)
print(f"  {what:<9} {path} (claudeMdExcludes: CLAUDE.md, AGENTS.md)")
PY
